def severity_badge(severity):
    """Returns an HTML badge colored by severity level."""
    return f'<span class="badge badge-{severity.lower()}">{severity}</span>'

def metric_card(label, value, variant):
    """Returns an HTML metric card with colored top bar."""
    return f"""
    <div class="metric-card metric-{variant}">
        <div class="metric-label">{label}</div>
        <div class="metric-value">{value}</div>
    </div>
    """

def generate_report(results):
    """Build a plain-text report for download."""
    lines = [
        "=" * 60, "  SECURESCANS AI — THREAT ANALYSIS REPORT", "=" * 60,
        f"  Scan Time     : {results['scan_time']}",
        f"  Input Size    : {results['input_length']:,} characters",
        f"  Risk Score    : {results['risk_score']}/100 ({results['risk_level']})",
        f"  Total Findings: {results['total_findings']}",
        "=" * 60, "", "SEVERITY BREAKDOWN", "-" * 40,
    ]
    for sev in ["Critical", "High", "Medium", "Low"]:
        lines.append(f"  {sev:10s} : {results['severity_counts'][sev]}")

    lines.extend(["", "DETAILED FINDINGS", "-" * 40])
    for f in results["findings"]:
        lines.append(f"\n  [{f['severity'].upper()}] {f['name']}")
        lines.append(f"  Category : {f['category']}  |  Matches : {f['count']}")
        for m in f["matches"][:10]:
            display = m if len(m) <= 60 else m[:57] + "..."
            lines.append(f"    → {display}")

    if results["remediation"]:
        lines.extend(["", "REMEDIATION RECOMMENDATIONS", "-" * 40])
        for tip in results["remediation"]:
            lines.append(f"  {tip}")

    lines.extend(["", "=" * 60, "  Report generated by SecureScan AI", "=" * 60])
    return "\n".join(lines)




